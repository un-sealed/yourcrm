/**
 * Conversation-intelligence tables (spec 37-ai-conversation-intelligence,
 * P0). Migration `0410_conversation_intelligence.sql`.
 *
 * Two tables:
 *
 *  - `conversationAnalyses` — one AI reading of one conversation: a
 *    summary, a sentiment signal, extracted action items or the key
 *    topics. Every row carries full attribution (provider, model, run id,
 *    tokens, latency) plus the cost-control facts (`sourceChars`,
 *    `analysedChars`, `truncated`).
 *  - `callTranscripts` — the text of a call or meeting. INGESTED, never
 *    produced here: this module does no audio processing.
 *
 * POLYMORPHIC SUBJECT, NO FOREIGN KEY
 * -----------------------------------
 * `subjectType` + `subjectId` name the conversation. Email threads,
 * WhatsApp conversations and calls belong to other modules, so `subjectId`
 * is a plain uuid with an index and no FK — the rule every cross-module
 * reference in this schema follows (`people.companyId`, `aiRuns.actorId`).
 * The domain service resolves a subject through the OWNING module's
 * service, which is what makes permission inheritance real.
 *
 * NO VISIBILITY COLUMN ON PURPOSE
 * -------------------------------
 * An analysis is readable exactly when its subject is, re-resolved on
 * every read. A copied `visibleTo` column would go stale the moment the
 * thread is reassigned.
 *
 * WHY TOKENS LIVE HERE AND NOT IN `ai_runs`
 * -----------------------------------------
 * `aiRuns.conversationId` is NOT NULL and references `aiConversations` —
 * an assistant chat thread, which an analysis does not have. So an
 * analysis keeps its own accounting and reuses the same column names, and
 * spec 38's usage rollups can UNION the two. `runId` is generated by this
 * module, appears on every audit row for the analysis, and references no
 * table.
 *
 * NEVER STORED HERE
 * -----------------
 * No prompt text, no transcript excerpt, no raw provider error body.
 * `output` is the model's structured answer only. `errorMessage` has had
 * every run of source text removed before it arrives.
 */

export const CONVERSATION_SUBJECT_TYPE_VALUES = [
  "email_thread",
  "whatsapp_conversation",
  "call",
] as const

export type ConversationSubjectTypeValue = (typeof CONVERSATION_SUBJECT_TYPE_VALUES)[number]

export function isConversationSubjectType(value: unknown): value is ConversationSubjectTypeValue {
  return (
    typeof value === "string" &&
    (CONVERSATION_SUBJECT_TYPE_VALUES as readonly string[]).includes(value)
  )
}

