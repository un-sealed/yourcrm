/** One AI reading of one conversation. */
export const conversationAnalyses = pgTable(
  "conversation_analyses",
  {
    ...baseColumns,
    ...workspaceColumn,
    /** Which kind of conversation. See the header. */
    subjectType: varchar("subject_type", { length: 32 }).notNull(),
    /** Email thread / WhatsApp conversation / call id. Plain uuid, no FK. */
    subjectId: uuid("subject_id").notNull(),
    analysisType: varchar("analysis_type", { length: 32 }).notNull(),
    status: varchar("status", { length: 16 }).notNull().default("queued"),
    /** Attribution (spec 37 §14). Null until the run completes. */
    providerId: varchar("provider_id", { length: 64 }),
    model: varchar("model", { length: 128 }),
    /** This module's own run id; carried by every audit row it writes. */
    runId: uuid("run_id"),
    /** The model's structured answer. Never the source conversation. */
    output: jsonb("output"),
    promptTokens: integer("prompt_tokens").notNull().default(0),
    completionTokens: integer("completion_tokens").notNull().default(0),
    totalTokens: integer("total_tokens").notNull().default(0),
    latencyMs: integer("latency_ms").notNull().default(0),
    /** Characters in the conversation before truncation. */
    sourceChars: integer("source_chars").notNull().default(0),
    /** Characters actually sent to the provider. */
    analysedChars: integer("analysed_chars").notNull().default(0),
    truncated: boolean("truncated").notNull().default(false),
    /** `users.id` of whoever asked. Plain uuid, no FK. */
    requestedBy: uuid("requested_by"),
    analysedAt: timestamp("analysed_at", { withTimezone: true }),
    errorCode: varchar("error_code", { length: 64 }),
    /** Redacted of all source text before it reaches this column. */
    errorMessage: varchar("error_message", { length: 500 }),
    correlationId: varchar("correlation_id", { length: 128 }),
  },
  (t) => [
    index("conversation_analyses_workspace_idx").on(t.workspaceId),
    // The detail query: every analysis of one conversation, newest first.
    index("conversation_analyses_subject_idx").on(
      t.workspaceId,
      t.subjectType,
      t.subjectId,
      t.createdAt,
    ),
    index("conversation_analyses_type_idx").on(t.workspaceId, t.analysisType, t.createdAt),
    index("conversation_analyses_status_idx").on(t.workspaceId, t.status, t.createdAt),
    index("conversation_analyses_run_idx").on(t.runId),
    check(
      "conversation_analyses_subject_type_chk",
      sql`${t.subjectType} IN ('email_thread', 'whatsapp_conversation', 'call')`,
    ),
    check(
      "conversation_analyses_type_chk",
      sql`${t.analysisType} IN ('summary', 'sentiment', 'action_items', 'key_topics')`,
    ),
    check(
      "conversation_analyses_status_chk",
      sql`${t.status} IN ('queued', 'succeeded', 'failed')`,
    ),
  ],
)

export type ConversationAnalysisRow = typeof conversationAnalyses.$inferSelect
export type NewConversationAnalysisRow = typeof conversationAnalyses.$inferInsert

/**
 * An ingested call/meeting transcript.
 *
 * THE SPEECH-TO-TEXT SEAM. Rows arrive either from a provider/notetaker
 * payload (`source = 'provider'`, `externalId` makes re-delivery
 * idempotent) or from a human paste (`source = 'manual'`). Wiring a real
 * STT provider means writing rows here through the same ingest path —
 * nothing downstream changes.
 */
export const callTranscripts = pgTable(
  "call_transcripts",
  {
    ...baseColumns,
    ...workspaceColumn,
    subjectType: varchar("subject_type", { length: 32 }).notNull().default("call"),
    /** Call / meeting id. Plain uuid, no FK. */
    subjectId: uuid("subject_id").notNull(),
    source: varchar("source", { length: 16 }).notNull(),
    /** Notetaker or STT provider. Null for a manual paste. */
    providerId: varchar("provider_id", { length: 64 }),
    /** Provider transcript id; unique per workspace (idempotent inbound). */
    externalId: varchar("external_id", { length: 255 }),
    language: varchar("language", { length: 16 }),
    text: text("text").notNull(),
    /** `[{ speaker, startMs, endMs, text }]`, as the provider reported it. */
    segments: jsonb("segments"),
    durationMs: integer("duration_ms"),
    speakerCount: integer("speaker_count").notNull().default(0),
    charCount: integer("char_count").notNull().default(0),
  },
  (t) => [
    index("call_transcripts_workspace_idx").on(t.workspaceId),
    index("call_transcripts_subject_idx").on(
      t.workspaceId,
      t.subjectType,
      t.subjectId,
      t.createdAt,
    ),
    uniqueIndex("call_transcripts_external_idx")
      .on(t.workspaceId, t.externalId)
      .where(sql`${t.externalId} IS NOT NULL AND ${t.deletedAt} IS NULL`),
    check(
      "call_transcripts_subject_type_chk",
      sql`${t.subjectType} IN ('email_thread', 'whatsapp_conversation', 'call')`,
    ),
    check("call_transcripts_source_chk", sql`${t.source} IN ('provider', 'manual')`),
  ],
)

export type CallTranscriptRow = typeof callTranscripts.$inferSelect
export type NewCallTranscriptRow = typeof callTranscripts.$inferInsert
