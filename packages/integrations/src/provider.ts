/**
 * `@yourcrm/integrations` — the provider contract.
 *
 * WHAT THIS IS
 * ------------
 * The single typed description of "a third-party system YourCRM can connect
 * to". Email, WhatsApp and calling adapters all implement THIS shape; the
 * framework (connection records, credential storage, health checks, webhook
 * ingestion) is written once against it and knows nothing about any vendor.
 *
 * Nothing in this package hardcodes a vendor list. Providers are registered
 * into a registry (see `./registry.ts`); the catalogue an API response shows
 * is whatever is registered at runtime.
 *
 * MIRRORED CONTRACT (read this before you change a type here)
 * -----------------------------------------------------------
 * `packages/crm/src/integrations/types.ts` declares `IntegrationProviderPort`
 * and friends as a *structural mirror* of the types below. That mirror exists
 * because `@yourcrm/crm` does not declare `@yourcrm/integrations` as a
 * dependency yet (bun workspaces symlink only declared deps, so the import
 * would not resolve — reported as a blocker to the integrator). The mirror is
 * the same pattern `packages/crm/src/ports.ts` already uses for
 * `WriteAuditInput`. Keep the two files in sync until the dependency is wired,
 * at which point the mirror collapses into a re-export.
 */

/**
 * Minimal structural shape of a config validator. Every zod schema satisfies
 * it (`z.object({...})`), and typing it structurally keeps the contract
 * mirrorable into `@yourcrm/crm` without a zod version coupling.
 */
export type IntegrationConfigSchema = {
  parse(value: unknown): unknown
}

/** Lifecycle state of one installed connection. Persisted verbatim. */
export const INTEGRATION_CONNECTION_STATUSES = ["connected", "disconnected", "error"] as const

export type IntegrationConnectionStatus = (typeof INTEGRATION_CONNECTION_STATUSES)[number]

export function isIntegrationConnectionStatus(
  value: unknown,
): value is IntegrationConnectionStatus {
  return (
    typeof value === "string" &&
    (INTEGRATION_CONNECTION_STATUSES as readonly string[]).includes(value)
  )
}

