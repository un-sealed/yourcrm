/**
 * Customer Success module (spec 46-customer-success, P0).
 *
 * Thin HTTP layer only: zod validation at the boundary, session from the
 * auth middleware, then straight into the domain service
 * (`@yourcrm/crm/src/customer-success`); `people.ts` is the golden
 * reference for the shape, `reports.ts` for the permission-filtered
 * aggregation shape.
 *
 * PLAYBOOK TASKS REUSE THE TASKS MODULE. `defaultService` below wires a
 * `TasksPort` onto the REAL tasks domain service (`createTasksService`,
 * same construction as `tasks.ts`'s own route file), so a playbook-created
 * task runs through normal task validation, audit and
 * `CrmEvents.TaskCreated` — this module never writes to the `tasks` table
 * directly and never re-implements a task engine.
 *
 * REGISTRY. `routes/modules/index.ts` is generated by `bun run gen:routes`;
 * this agent must not edit or regenerate it (same rule the unified-inbox
 * module documents), so the integrator's generator run is what mounts
 * `/api/v1/customer-success`. The exports below (`basePath`,
 * `createRoutes`, `openApiPaths`) are the contract that generator reads.
 */

