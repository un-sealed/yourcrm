let moduleService: SalesSequenceService | null = null
const resolveModuleService = (): SalesSequenceService => (moduleService ??= defaultService())

function serviceContextOf(c: Context<AppEnv>) {
  const session = c.get("session") as Session | null
  return {
    workspaceId: session?.workspaceId ?? "",
    actorId: session?.user.id ?? "",
    role: session ? roleInWorkspace(session) : "viewer",
    correlationId: c.get("requestId") as string | undefined,
  }
}

const STATUS_BY_CODE: Record<string, 400 | 403 | 404 | 409 | 422> = {
  NOT_FOUND: 404,
  INVALID_SEQUENCE: 400,
  SEQUENCE_NOT_ENROLLABLE: 422,
  SEQUENCE_CONTACT_SUPPRESSED: 409,
  SEQUENCE_STEP_FAILED: 422,
}

function mapError(c: Context<AppEnv>, err: unknown) {
  const requestId = c.get("requestId") as string | undefined
  if (err instanceof PermissionDeniedError) {
    return c.json(errorEnvelope("FORBIDDEN", err.message, requestId), 403)
  }
  if (err instanceof z.ZodError) {
    return c.json(
      errorEnvelope("VALIDATION_ERROR", "Invalid request body", requestId, err.flatten()),
      400,
    )
  }
  if (err instanceof Error) {
    const code = (err as { code?: string }).code
    const status = code ? STATUS_BY_CODE[code] : undefined
    if (code && status) return c.json(errorEnvelope(code, err.message, requestId), status)
  }
  throw err
}

function invalidBody(c: Context, result: { error: { flatten(): unknown } }) {
  return c.json(
    errorEnvelope(
      "VALIDATION_ERROR",
      "Invalid request body",
      c.req.header("x-request-id") ?? undefined,
      result.error.flatten(),
    ),
    400,
  )
}

function invalidQuery(c: Context, result: { error: { flatten(): unknown } }) {
  return c.json(
    errorEnvelope(
      "VALIDATION_ERROR",
      "Invalid query parameters",
      c.req.header("x-request-id") ?? undefined,
      result.error.flatten(),
    ),
    400,
  )
}

export function createRoutes(deps: SequencesRouteDeps = {}) {
  const app = new Hono<AppEnv>()
  // Lazy default wiring: route construction must never touch the database —
  // registry and full-app tests mount every module without a live Postgres.
  let cached: SalesSequenceService | null = deps.service ?? null
  const service = () => (cached ??= resolveModuleService())

  // Static segments first: `/catalogue`, `/enrollments` and `/unsubscribe`
  // must not be swallowed by `/:id`.
  app.get("/catalogue", requireSession(), (c) => c.json({ data: describeSalesSequenceCatalogue() }))

  app.get(
    "/enrollments",
    requireSession(),
    zValidator("query", salesSequenceEnrollmentQuerySchema, (result, c) => {
      if (!result.success) return invalidQuery(c, result)
    }),
    async (c) => {
      try {
        return c.json(await service().listEnrollments(serviceContextOf(c), c.req.valid("query")))
      } catch (err) {
        return mapError(c, err)
      }
    },
  )

  app.get("/enrollments/:enrollmentId", requireSession(), async (c) => {
    try {
      const detail = await service().getEnrollment(serviceContextOf(c), c.req.param("enrollmentId"))
      return c.json({ data: { ...detail.enrollment, runs: detail.runs } })
    } catch (err) {
      return mapError(c, err)
    }
  })

  app.post("/enrollments/:enrollmentId/pause", requireSession(), async (c) => {
    try {
      const paused = await service().pauseEnrollment(
        serviceContextOf(c),
        c.req.param("enrollmentId"),
      )
      return c.json({ data: paused })
    } catch (err) {
      return mapError(c, err)
    }
  })

  app.post("/enrollments/:enrollmentId/resume", requireSession(), async (c) => {
    try {
      const resumed = await service().resumeEnrollment(
        serviceContextOf(c),
        c.req.param("enrollmentId"),
      )
      return c.json({ data: resumed })
    } catch (err) {
      return mapError(c, err)
    }
  })

  // Removing somebody is a STOP, not a delete: the enrollment stays, with
  // the reason it ended, so the audit trail survives.
  app.post(
    "/enrollments/:enrollmentId/stop",
    requireSession(),
    zValidator("json", stopSalesSequenceEnrollmentSchema, (result, c) => {
      if (!result.success) return invalidBody(c, result)
    }),
    async (c) => {
      try {
        const stopped = await service().stopEnrollment(
          serviceContextOf(c),
          c.req.param("enrollmentId"),
          c.req.valid("json"),
        )
        return c.json({ data: stopped })
      } catch (err) {
        return mapError(c, err)
      }
    },
  )

  // Workspace-wide opt-out: stops every live drip for this contact and
  // blocks re-enrolment anywhere.
  app.post(
    "/unsubscribe",
    requireSession(),
    zValidator("json", unsubscribeFromSalesSequencesSchema, (result, c) => {
      if (!result.success) return invalidBody(c, result)
    }),
    async (c) => {
      try {
        return c.json({
          data: await service().unsubscribe(serviceContextOf(c), c.req.valid("json")),
        })
      } catch (err) {
        return mapError(c, err)
      }
    },
  )

  app.get(
    "/",
    requireSession(),
    zValidator("query", salesSequenceQuerySchema, (result, c) => {
      if (!result.success) return invalidQuery(c, result)
    }),
    async (c) => {
      try {
        return c.json(await service().list(serviceContextOf(c), c.req.valid("query")))
      } catch (err) {
        return mapError(c, err)
      }
    },
  )

  app.post(
    "/",
    requireSession(),
    zValidator("json", createSalesSequenceSchema, (result, c) => {
      if (!result.success) return invalidBody(c, result)
    }),
    async (c) => {
      try {
        const sequence = await service().create(serviceContextOf(c), c.req.valid("json"))
        return c.json({ data: sequence }, 201)
      } catch (err) {
        return mapError(c, err)
      }
    },
  )

  app.get("/:id", requireSession(), async (c) => {
    try {
      const detail = await service().get(serviceContextOf(c), c.req.param("id"))
      return c.json({ data: { ...detail.sequence, steps: detail.steps } })
    } catch (err) {
      return mapError(c, err)
    }
  })

  app.patch(
    "/:id",
    requireSession(),
    zValidator("json", updateSalesSequenceSchema, (result, c) => {
      if (!result.success) return invalidBody(c, result)
    }),
    async (c) => {
      try {
        const sequence = await service().update(
          serviceContextOf(c),
          c.req.param("id"),
          c.req.valid("json"),
        )
        return c.json({ data: sequence })
      } catch (err) {
        return mapError(c, err)
      }
    },
  )

  app.delete("/:id", requireSession(), async (c) => {
    try {
      await service().softDelete(serviceContextOf(c), c.req.param("id"))
      return c.json({ data: { deleted: true } })
    } catch (err) {
      return mapError(c, err)
    }
  })

  app.post("/:id/restore", requireSession(), async (c) => {
    try {
      return c.json({ data: await service().restore(serviceContextOf(c), c.req.param("id")) })
    } catch (err) {
      return mapError(c, err)
    }
  })

  app.put(
    "/:id/steps",
    requireSession(),
    zValidator("json", replaceSalesSequenceStepsSchema, (result, c) => {
      if (!result.success) return invalidBody(c, result)
    }),
    async (c) => {
      try {
        const steps = await service().replaceSteps(
          serviceContextOf(c),
          c.req.param("id"),
          c.req.valid("json"),
        )
        return c.json({ data: steps })
      } catch (err) {
        return mapError(c, err)
      }
    },
  )

  // Activating needs `send_external` — it is what makes the sequence start
  // sending. Pausing only needs `update`. See the service's `access.ts`.
  app.post(
    "/:id/status",
    requireSession(),
    zValidator("json", setStatusSchema, (result, c) => {
      if (!result.success) return invalidBody(c, result)
    }),
    async (c) => {
      try {
        const sequence = await service().setStatus(
          serviceContextOf(c),
          c.req.param("id"),
          c.req.valid("json").status,
        )
        return c.json({ data: sequence })
      } catch (err) {
        return mapError(c, err)
      }
    },
  )

  app.post(
    "/:id/enrollments",
    requireSession(),
    zValidator("json", enrollInSalesSequenceSchema, (result, c) => {
      if (!result.success) return invalidBody(c, result)
    }),
    async (c) => {
      try {
        const result = await service().enroll(
          serviceContextOf(c),
          c.req.param("id"),
          c.req.valid("json"),
        )
        // 200 rather than 201 when the person was already enrolled: the
        // call is idempotent and created nothing.
        return c.json({ data: result.enrollment }, result.created ? 201 : 200)
      } catch (err) {
        return mapError(c, err)
      }
    },
  )

  app.get("/:id/enrollments", requireSession(), async (c) => {
    try {
      return c.json(
        await service().listEnrollments(serviceContextOf(c), { sequenceId: c.req.param("id") }),
      )
    } catch (err) {
      return mapError(c, err)
    }
  })

  app.get("/:id/stats", requireSession(), async (c) => {
    try {
      return c.json({ data: await service().stats(serviceContextOf(c), c.req.param("id")) })
    } catch (err) {
      return mapError(c, err)
    }
  })

  return app
}

/**
 * Bootstrap hook: connect the in-process event bus to the exit watcher, so
 * an inbound reply or bounce actually stops the drip. Call it ONCE from
 * `apps/api/src/index.ts`; route factories must not subscribe (see the
 * file header).
 *
 * Without this call the module still stops on unsubscribe and on manual
 * removal, but NOT on reply — which is the one thing it must do. It is the
 * single most important line of the integration.
 */
export function subscribeSalesSequenceExitWatcher(service?: SalesSequenceService): () => void {
  // Resolve the service lazily, on the first event — NOT at boot. A
  // default parameter of `defaultService()` evaluates immediately, which
  // calls getDb() during module bootstrap and crashes the API before it
  // can serve anything. Every other module defers construction the same way.
  let resolved: SalesSequenceService | undefined = service
  const lazy = new Proxy({} as SalesSequenceService, {
    get(_t, prop: string | symbol) {
      resolved ??= resolveModuleService()
      return Reflect.get(resolved as object, prop, resolved)
    },
  })
  return subscribeSalesSequenceExits(getEventBus(), lazy, (err) => {
    console.error(
      JSON.stringify({ level: "error", msg: "sequence_exit_check_failed", err: String(err) }),
    )
  })
}

