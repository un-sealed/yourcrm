/**
 * Sales engagement / sequences module (spec 47-sales-engagement, P0).
 *
 * Thin HTTP layer only: zod validation at the boundary, session from the
 * auth middleware, then straight into the domain service. The interesting
 * parts — exit conditions, step idempotency, permission inheritance — all
 * live in `@yourcrm/crm/src/sequences`; this file only BINDS them:
 *
 *   store            -> sequences repository (migration 0270)
 *   audit            -> writeAudit
 *   resolveActorRole -> the memberships table (the owner's LIVE role)
 *   resolveContact   -> the people repository (never an invented address)
 *   queue            -> the sequence-step queue seam
 *   executor         -> the EMAIL and TASKS domain services, so no business
 *                       rule is duplicated here
 *
 * REGISTRY. `routes/modules/index.ts` is generated by `bun run gen:routes`;
 * this agent must not edit or regenerate it, so the integrator's generator
 * run is what mounts `/api/v1/sequences`. The exports below (`basePath`,
 * `createRoutes`, `openApiPaths`) are the contract that generator reads.
 *
 * INTEGRATION NOTES (both are dependency blockers an agent may not fix,
 * because they require editing `package.json` or another module's file):
 *
 *  1. `@yourcrm/api` cannot import `bullmq`, so `defaultQueue()` records
 *     the enqueue as a structured log line instead of pushing to BullMQ,
 *     and enrollments sit at their current step. `apps/worker` already
 *     registers the handler (`sequence.step`); swapping in the real
 *     adapter is a four-line change in one function — nothing else moves.
 *     Identical to `automation.ts`'s `defaultQueue()`.
 *  2. `defaultEmailService()` below duplicates `email.ts`'s private
 *     `defaultService()` composition, because that module exports no
 *     factory and this agent may not edit its file. It is wiring, not
 *     logic — every rule still lives in `createEmailService` — but the
 *     integrator should export one shared factory and delete this copy.
 */

